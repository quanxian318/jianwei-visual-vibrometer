"""Designs the FIR stage of the PDM decimator (src/measure/pdm_model.cpp, fed by
the PL receiver ax7010/pl/audio/rtl/pdm_mic.v) and writes its coefficient
table src/measure/pdm_fir_coef.inc.

Chain: 2 MHz PDM -> CIC (order 5, /32) -> 62.5 kHz -> this FIR (/2) -> 31.25 kHz.
FIR: 63 taps, linear phase, weighted least squares. The passband 0..10 kHz
equalises the CIC droop; the stopband starts at 15.625 kHz, the output Nyquist
frequency, so nothing aliases into the output band. Coefficients are Q17 with
their sum forced to 2^17 (DC gain 1).

usage: python pdm_fir_design.py      (numpy; prints the response of the chain)
"""
import pathlib

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
INC = ROOT / 'src' / 'measure' / 'pdm_fir_coef.inc'

FS_PDM = 2.0e6
CIC_R, CIC_N = 32, 5
FS_IN = FS_PDM / CIC_R      # FIR input rate, 62.5 kHz
FS_OUT = FS_IN / 2          # 31.25 kHz
TAPS = 63
F_PASS, F_STOP = 10e3, FS_OUT / 2
FRAC = 17                   # Q17, 18-bit signed coefficients
STOP_WEIGHT = 300.0


def cic(f):
    """CIC magnitude, 1 at DC."""
    x = np.pi * np.asarray(f, dtype=float) / FS_PDM
    s = np.sin(x)
    r = np.ones_like(x)
    nz = np.abs(s) > 1e-15
    r[nz] = np.sin(CIC_R * x[nz]) / (CIC_R * s[nz])
    return np.abs(r) ** CIC_N


def fir_response(h, f):
    w = 2 * np.pi * np.asarray(f, dtype=float) / FS_IN
    n = np.arange(len(h))
    return np.abs(np.exp(-1j * np.outer(w, n)) @ h)


def design():
    m = (TAPS - 1) // 2
    f = np.linspace(0, FS_IN / 2, 6000)
    w = 2 * np.pi * f / FS_IN
    passband, stopband = f <= F_PASS, f >= F_STOP
    basis = np.cos(np.outer(w, np.arange(m + 1)))  # a0 + sum a_k cos(k w)
    want = np.where(passband, 1.0 / cic(f), 0.0)
    weight = np.sqrt(np.where(passband, 1.0, np.where(stopband, STOP_WEIGHT, 0.0)))
    a, *_ = np.linalg.lstsq(basis * weight[:, None], want * weight, rcond=None)
    h = np.zeros(TAPS)
    h[m] = a[0]
    for k in range(1, m + 1):
        h[m - k] = h[m + k] = a[k] / 2
    return h


def quantise(h):
    q = np.round(h / h.sum() * (1 << FRAC)).astype(np.int64)
    q[TAPS // 2] += (1 << FRAC) - q.sum()  # DC gain exactly 1
    assert q.sum() == 1 << FRAC and np.all(np.abs(q) < 1 << FRAC)
    assert np.array_equal(q, q[::-1])
    return q


def report(q):
    h = q / float(1 << FRAC)
    fp = np.linspace(20, F_PASS, 2000)
    ripple = 20 * np.log10(cic(fp) * fir_response(h, fp))
    fs = np.linspace(F_STOP, FS_IN / 2, 2000)
    stop = 20 * np.log10(np.max(fir_response(h, fs)))
    # Everything that lands in 0..10 kHz after both decimations.
    worst = 0.0
    for k in range(1, int(FS_PDM / 2 / FS_OUT) + 1):
        f = np.linspace(k * FS_OUT - F_PASS, k * FS_OUT + F_PASS, 400)
        f = f[(f > 0) & (f < FS_PDM / 2)]
        worst = max(worst, float(np.max(cic(f) * fir_response(h, np.mod(f, FS_IN)))))
    delay_us = (CIC_N * (CIC_R - 1) / 2 / FS_PDM + (TAPS - 1) / 2 / FS_IN) * 1e6
    print(f'passband 20 Hz..10 kHz: {ripple.min():+.3f} .. {ripple.max():+.3f} dB')
    print(f'FIR stopband from {F_STOP:.0f} Hz: {stop:.1f} dB')
    print(f'worst alias into 0..10 kHz: {20 * np.log10(worst):.1f} dB')
    print(f'group delay: {delay_us:.2f} us (CIC {CIC_N * (CIC_R - 1) / 2:.1f} PDM bits, FIR {(TAPS - 1) // 2} taps)')


def write(q):
    body = ['// Generated by linux/vibmon/tools/pdm_fir_design.py - do not edit.',
            f'// {TAPS} taps, Q{FRAC}, sum {1 << FRAC} (DC gain 1): CIC (order 5, /32) droop equalised',
            '// to 10 kHz, stopband from 15.625 kHz.']
    for i in range(0, TAPS, 8):
        body.append(' '.join(f'{int(v)},' for v in q[i:i + 8]))
    INC.write_text('\n'.join(body) + '\n', encoding='utf-8', newline='\n')
    print(f'wrote {INC.name}')


def main():
    q = quantise(design())
    report(q)
    write(q)


if __name__ == '__main__':
    main()
