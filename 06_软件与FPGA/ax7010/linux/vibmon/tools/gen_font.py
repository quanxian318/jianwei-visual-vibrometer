"""Generate src/gfx/font_data.inc: 4-bit anti-aliased glyphs for the UI and the
printed report. Character set = printable ASCII + every non-ASCII character
that appears in src/**/*.cpp|h (so new UI strings need a re-run).

usage: python gen_font.py [medium.otf bold.otf]   (needs Pillow; run on the build PC)
Fonts: Noto Sans SC Medium and Bold (SIL Open Font License 1.1).
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'src' / 'gfx' / 'font_data.inc'
DEFAULT_FONTS = {
    'medium': [r'C:\Windows\Fonts\Noto Sans SC Medium (TrueType).otf',
               '/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc'],
    'bold': [r'C:\Windows\Fonts\Noto Sans SC Bold (TrueType).otf',
             '/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc'],
}
# (pixel size, weight, include CJK)
SIZES = [(14, 'medium', True), (18, 'medium', True), (22, 'medium', True), (26, 'medium', True),
         (22, 'bold', True), (32, 'bold', True), (44, 'bold', False)]
EXTRA = '°±·×—–µ…−≈↑↓←→▲▼'


def source_chars():
    chars = set()
    for p in sorted((ROOT / 'src').rglob('*')):
        if p.suffix in ('.cpp', '.h') and p.name != 'font_data.inc':
            for ch in p.read_text(encoding='utf-8'):
                if ord(ch) > 0x7E:
                    chars.add(ch)
    return chars


def render(font_path, size, chars):
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in sorted(chars, key=ord):
        x0, y0, x1, y1 = font.getbbox(ch, anchor='la')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(font.getlength(ch)))
        offset = len(bitmap)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='la')
            levels = [(v + 8) // 17 for v in img.tobytes()]
            if len(levels) % 2:
                levels.append(0)
            for i in range(0, len(levels), 2):
                bitmap.append((levels[i] << 4) | levels[i + 1])
        glyphs.append((ord(ch), w, h, x0, y0, adv, offset))
    return ascent + descent, ascent, glyphs, bitmap


def main():
    fonts = {}
    for i, weight in enumerate(('medium', 'bold')):
        if len(sys.argv) > 1 + i:
            fonts[weight] = sys.argv[1 + i]
        else:
            fonts[weight] = next(f for f in DEFAULT_FONTS[weight] if pathlib.Path(f).exists())
    cjk = source_chars() | set(EXTRA)
    ascii_set = {chr(c) for c in range(0x20, 0x7F)}
    out = ['// Generated by tools/gen_font.py from %s and %s - do not edit.' % (
               pathlib.Path(fonts['medium']).name, pathlib.Path(fonts['bold']).name),
           '// Glyph outlines: Noto Sans SC, SIL Open Font License 1.1.', '']
    faces = []
    for size, weight, with_cjk in SIZES:
        chars = ascii_set | (cjk if with_cjk else set(EXTRA))
        line_h, ascent, glyphs, bitmap = render(fonts[weight], size, chars)
        tag = '%s%d' % (weight[0].upper(), size)
        out.append('static const FontGlyph kGlyphs%s[] = {' % tag)
        for g in glyphs:
            out.append('    {0x%04X, %d, %d, %d, %d, %d, %d},' % g)
        out.append('};')
        out.append('static const uint8_t kBitmap%s[] =' % tag)
        hexs = ''.join('\\x%02x' % b for b in bitmap) or '\\x00'
        for i in range(0, len(hexs), 160):
            out.append('    "%s"' % hexs[i:i + 160])
        out.append('    ;')
        out.append('static const FontFace kFace%s = {%d, %d, %d, %s, kGlyphs%s, %d, kBitmap%s};' % (
            tag, size, line_h, ascent, 'true' if weight == 'bold' else 'false', tag, len(glyphs), tag))
        out.append('')
        faces.append('&kFace%s' % tag)
        print('%s: %d glyphs, %d bitmap bytes' % (tag, len(glyphs), len(bitmap)))
    out.append('static const FontFace* const kFaces[] = {%s};' % ', '.join(faces))
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('wrote', OUT, 'with', len(cjk), 'non-ASCII characters')


if __name__ == '__main__':
    main()
